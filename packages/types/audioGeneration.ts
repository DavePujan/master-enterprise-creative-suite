export interface SpeakerDefinition {
  name: string; // e.g. "Host" or "Speaker 1"
  voice: OfficialGeminiVoice;
  role?: string;
}

export interface VoiceConfig {
  speakerMode: "single" | "two-speaker";
  speakers: [SpeakerDefinition] | [SpeakerDefinition, SpeakerDefinition];
}

export type VoiceEmotion =
  | "Neutral"
  | "Professional"
  | "Cheerful"
  | "Energetic"
  | "Calming"
  | "Dramatic"
  | "Authoritative";

export type VoicePace = "normal" | "fast" | "deliberate" | "slow";

export interface PerformanceConfig {
  emotion?: VoiceEmotion;
  pace?: VoicePace;
  accent?: string; // e.g. "Indian English", "Hinglish", "British RP", "Neutral American"
  style?: string; // e.g. "cinematic trailer", "podcast interview", "commercial promo"
  tagsEnabled?: boolean;
}

export interface VoiceoverRequest {
  generationType: "voiceover";
  userIntent: string;
  brandContext?: BrandContextSnapshot;
  transcript?: string; // If supplied, directly synthesized; if not, generated by Scriptwriter
  languageCode?: string; // BCP-47 e.g. "en-US", "hi-IN", "gu-IN", "mr-IN"
  targetDurationSeconds?: number;
  voiceConfig: VoiceConfig;
  performanceConfig?: PerformanceConfig;
  idempotencyKey?: string;
}

export interface VoiceoverResult {
  audioBase64: string;
  mimeType: "audio/wav";
  transcript: string;
  durationSeconds: number;
  voice: OfficialGeminiVoice;
  speakers: SpeakerDefinition[];
  modelUsed: string;
  storageUrl?: string;
  storagePath?: string;
}

export type MusicMode = "clip" | "full-track";

export interface MusicRequest {
  generationType: "music";
  prompt: string;
  mode: MusicMode;
  genre?: string;
  mood?: string;
  tempoBpm?: number;
  keyScale?: string;
  instrumentation?: string[];
  vocalsMode?: "instrumental" | "with-vocals";
  lyrics?: string;
  structureNotes?: string;
  imageReferences?: AudioAssetReference[];
  preferredFormat?: "mp3" | "wav";
  idempotencyKey?: string;
}

export interface MusicResult {
  audioBase64: string;
  mimeType: "audio/mp3" | "audio/wav";
  mode: MusicMode;
  durationSeconds: number;
  lyrics?: string;
  structure?: string;
  modelUsed: string;
  storageUrl?: string;
  storagePath?: string;
}

export type AudioGenerationRequest = VoiceoverRequest | MusicRequest;

export interface AudioGenerationResponse {
  success: boolean;
  generationType: AudioGenerationType;
  voiceoverResult?: VoiceoverResult;
  musicResult?: MusicResult;
  modelUsed: string;
  creditsCharged: number;
  newBalance?: number;
  fallbackUsed?: boolean;
  fallbackReason?: string;
}
